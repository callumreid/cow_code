const render = (modules: boolean[][]) => modules.map((row) => row.map((dark) => (dark ? "1" : "0")).join(""))

describe("qrEncode", () => {
  test("matches reference matrices module-for-module", () => {
    for (const fixture of fixtures) {
      expect(render(qrEncode(fixture.text))).toEqual(fixture.rows)
    }
  })

  test("selects the smallest version that fits", () => {
    expect(qrEncode("x".repeat(14)).length).toBe(21) // version 1
    expect(qrEncode("x".repeat(15)).length).toBe(25) // version 2
    expect(qrEncode("x".repeat(213)).length).toBe(57) // version 10
  })

  test("throws beyond version 10 capacity", () => {
    expect(() => qrEncode("x".repeat(214))).toThrow()
  })

  test("encodes multi-byte UTF-8 payloads", () => {
    const modules = qrEncode("üñïçødé ✓ テスト")
    expect(modules.length).toBeGreaterThanOrEqual(21)
    expect(modules.every((row) => row.length === modules.length)).toBe(true)
  })
})

describe("qrSvgPath", () => {
  test("draws one unit square per dark module", () => {
    const modules = qrEncode("hello")
    const dark = modules.flat().filter((module) => module).length
    expect(qrSvgPath(modules).split("M").length - 1).toBe(dark)
    expect(qrSvgPath(modules)).toContain("M0 0h1v1h-1z") // finder corner
  })
})
